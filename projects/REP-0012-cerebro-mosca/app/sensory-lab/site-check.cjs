const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const base=process.env.TEST_BASE || 'http://127.0.0.1:8774';
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const result={base,checked:new Date().toISOString(),errors:[],failedResponses:[],checks:[]};
 try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>result.errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)result.failedResponses.push({url:r.url(),status:r.status()});});
  await page.goto(base+'/cerebro-mosca/');
  assert.equal(await page.locator('nav a').count(),4);
  await page.getByRole('link',{name:/Abrir FlyBrain/}).click();
  await page.waitForFunction(()=>window.BRAIN?.workerReady,{},{timeout:60000});
  await page.locator('#brain3dBtn').click();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('#brain3dBtn').getAttribute('aria-pressed'),'true');
  result.checks.push('FlyBrain loads the full worker; Brain 3D opens');
  await page.getByRole('link',{name:'Acessos',exact:true}).click();
  await page.getByRole('link',{name:/Mapa de respostas/}).click();
  await page.locator('#condition').selectOption('food');
  await page.waitForFunction(()=>document.getElementById('status').textContent.includes('7 disparos fora'));
  assert.equal(await page.locator('#rows tr').count(),148);
  await page.locator('#ablation').selectOption('true');
  assert.equal(await page.locator('#rows tr').count(),0);
  result.checks.push('Neuron map shows food response and empty ablation control');
  await page.goto(base+'/cerebro-mosca/guide-demo/');
  await page.waitForURL('**/guide-demo/');
  await page.waitForFunction(()=>window.GuideDemo?.sensoryAdapter?.ready,{},{timeout:60000});
  await page.locator('#openBench').click();
  await page.locator('#blankStimuli').click();
  await page.waitForTimeout(1200);
  assert.ok(await page.evaluate(()=>GuideDemo.getNeuralSamples().every(s=>s.activity.every(g=>g.spikes===0))));
  await page.locator('#stim-food').fill('0.3');
  await page.locator('#applyStimuli').click();
  await page.waitForTimeout(3000);
  assert.ok(await page.evaluate(()=>GuideDemo.getNeuralSamples().some(s=>s.activity.some(g=>g.name==='OLF_ORN_FOOD'&&g.spikes>0))));
  const download=page.waitForEvent('download');await page.locator('#exportStimuli').click();
  const file=await(await download).path();assert.ok(JSON.parse(fs.readFileSync(file,'utf8')).samples.length>0);
  result.checks.push('Game link stays on game; blank/food/export controls work');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.ok(await page.locator('#closeBench').isVisible());
  await page.screenshot({path:path.join(__dirname,'site-mobile.png')});
  await page.goto(base+'/cerebro-mosca/');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(__dirname,'portal-mobile.png')});
  await page.getByRole('link',{name:/Abrir FlyBrain/}).click();
  await page.waitForFunction(()=>window.BRAIN?.workerReady,{},{timeout:60000});
  await page.locator('#brain3dBtn').click();
  assert.equal(await page.locator('#brain3dBtn').getAttribute('aria-pressed'),'true');
  await page.screenshot({path:path.join(__dirname,'brain-mobile.png')});
  result.checks.push('Portal and bench fit mobile viewport');
  result.checks.push('FlyBrain Brain 3D is accessible on mobile');
  assert.deepEqual(result.errors,[]);assert.deepEqual(result.failedResponses,[]);
  result.passed=true;
 } finally {fs.writeFileSync(path.join(__dirname,'site-check.json'),JSON.stringify(result,null,2));await browser.close();}
 console.log(JSON.stringify(result,null,2));
})().catch(e=>{console.error(e);process.exitCode=1;});
